// Dosya: 07_02_sayi_yazimlari.dart
void main() {
  int nufus = 1_000_000;    // Basamak ayırıcı: okunabilirlik için
  int renk = 0xFF2196F3;    // Onaltılık (hexadecimal) yazım
  double kucuk = 1.5e-3;    // Bilimsel gösterim: 1.5 × 10⁻³
  double buyuk = 2e6;       // 2 × 10⁶

  print(nufus);
  print(renk);
  print(kucuk);
  print(buyuk);
}
