void main() {
  int bildirimSayisi = 3;
  print('Başlangıç: $bildirimSayisi');

  bildirimSayisi = 5;
  print('Yeni bildirimler geldi: $bildirimSayisi');

  bildirimSayisi = bildirimSayisi + 1;
  print('Bir tane daha: $bildirimSayisi');

  bildirimSayisi = 0;
  print('Hepsi okundu: $bildirimSayisi');
}
